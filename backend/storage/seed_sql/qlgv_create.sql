-- Hai khoa ngoai vong KHOA.TRGKHOA -> GIAOVIEN va LOP.TRGLOP -> HOCVIEN khong khai bao o day
-- (khong the nap du lieu theo thu tu bat ky); chung la hai cau hoi DDL rieng.
CREATE TABLE KHOA (
    MAKHOA VARCHAR(4) NOT NULL PRIMARY KEY,
    TENKHOA VARCHAR(40) NOT NULL,
    NGTLAP SMALLDATETIME NULL,
    TRGKHOA CHAR(4) NULL
);

CREATE TABLE MONHOC (
    MAMH VARCHAR(10) NOT NULL PRIMARY KEY,
    TENMH VARCHAR(40) NOT NULL,
    TCLT TINYINT NULL,
    TCTH TINYINT NULL,
    MAKHOA VARCHAR(4) NULL,
    FOREIGN KEY (MAKHOA) REFERENCES KHOA(MAKHOA)
);

CREATE TABLE DIEUKIEN (
    MAMH VARCHAR(10) NOT NULL,
    MAMH_TRUOC VARCHAR(10) NOT NULL,
    PRIMARY KEY (MAMH, MAMH_TRUOC),
    FOREIGN KEY (MAMH) REFERENCES MONHOC(MAMH),
    FOREIGN KEY (MAMH_TRUOC) REFERENCES MONHOC(MAMH)
);

CREATE TABLE GIAOVIEN (
    MAGV CHAR(4) NOT NULL PRIMARY KEY,
    HOTEN VARCHAR(40) NOT NULL,
    HOCVI VARCHAR(10) NULL,
    HOCHAM VARCHAR(10) NULL,
    GIOITINH VARCHAR(3) NULL,
    NGSINH SMALLDATETIME NULL,
    NGVL SMALLDATETIME NULL,
    HESO NUMERIC(4,2) NULL,
    MUCLUONG MONEY NULL,
    MAKHOA VARCHAR(4) NULL,
    FOREIGN KEY (MAKHOA) REFERENCES KHOA(MAKHOA)
);

CREATE TABLE LOP (
    MALOP CHAR(3) NOT NULL PRIMARY KEY,
    TENLOP VARCHAR(40) NOT NULL,
    TRGLOP CHAR(5) NULL,
    SISO TINYINT NULL,
    MAGVCN CHAR(4) NULL,
    FOREIGN KEY (MAGVCN) REFERENCES GIAOVIEN(MAGV)
);

CREATE TABLE HOCVIEN (
    MAHV CHAR(5) NOT NULL PRIMARY KEY,
    HO VARCHAR(40) NOT NULL,
    TEN VARCHAR(10) NOT NULL,
    NGSINH SMALLDATETIME NULL,
    GIOITINH VARCHAR(3) NULL,
    NOISINH VARCHAR(40) NULL,
    MALOP CHAR(3) NULL,
    GHICHU VARCHAR(50) NULL,
    DIEMTB NUMERIC(4,2) NULL,
    XEPLOAI VARCHAR(5) NULL,
    FOREIGN KEY (MALOP) REFERENCES LOP(MALOP)
);

CREATE TABLE GIANGDAY (
    MALOP CHAR(3) NOT NULL,
    MAMH VARCHAR(10) NOT NULL,
    MAGV CHAR(4) NOT NULL,
    HOCKY TINYINT NOT NULL,
    NAM SMALLINT NOT NULL,
    TUNGAY SMALLDATETIME NULL,
    DENNGAY SMALLDATETIME NULL,
    PRIMARY KEY (MALOP, MAMH),
    FOREIGN KEY (MALOP) REFERENCES LOP(MALOP),
    FOREIGN KEY (MAMH) REFERENCES MONHOC(MAMH),
    FOREIGN KEY (MAGV) REFERENCES GIAOVIEN(MAGV)
);

CREATE TABLE KETQUATHI (
    MAHV CHAR(5) NOT NULL,
    MAMH VARCHAR(10) NOT NULL,
    LANTHI TINYINT NOT NULL,
    NGTHI SMALLDATETIME NULL,
    DIEM NUMERIC(4,2) NULL,
    KQUA VARCHAR(10) NULL,
    PRIMARY KEY (MAHV, MAMH, LANTHI),
    FOREIGN KEY (MAHV) REFERENCES HOCVIEN(MAHV),
    FOREIGN KEY (MAMH) REFERENCES MONHOC(MAMH)
);
