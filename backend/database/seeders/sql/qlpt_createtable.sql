CREATE TABLE PHONGTRO (
    MaPT CHAR(5) NOT NULL,
    TenPT NVARCHAR(50),
    DienTich FLOAT,
    LoaiPT NVARCHAR(15),
    GiaPT MONEY,
    TinhTrangPT NVARCHAR(20),
    CONSTRAINT PK_PHONGTRO PRIMARY KEY (MaPT)
);

CREATE TABLE CUDAN (
    MaCD CHAR(5) NOT NULL,
    HoTen NVARCHAR(50),
    CCCD NVARCHAR(12),
    DiaChi NVARCHAR(100),
    SoDT VARCHAR(15),
    NgayThue SMALLDATETIME,
    TrangThaiCD NVARCHAR(15),
    CONSTRAINT PK_CUDAN PRIMARY KEY (MaCD)
);

CREATE TABLE HOPDONG (
    MaHD CHAR(5) NOT NULL,
    MaCD CHAR(5),
    MaPT CHAR(5),
    NgayKy SMALLDATETIME,
    NgayHetHan SMALLDATETIME,
    TrangThaiHD NVARCHAR(20),
    CONSTRAINT PK_HOPDONG PRIMARY KEY (MaHD),
    CONSTRAINT FK_HOPDONG_CUDAN FOREIGN KEY (MaCD) REFERENCES CUDAN (MaCD),
    CONSTRAINT FK_HOPDONG_PHONGTRO FOREIGN KEY (MaPT) REFERENCES PHONGTRO (MaPT)
);

CREATE TABLE DICHVU (
    MaDV CHAR(5) NOT NULL,
    TenDV NVARCHAR(50),
    DonGia MONEY,
    CONSTRAINT PK_DICHVU PRIMARY KEY (MaDV)
);

CREATE TABLE PHIEUTINHTIEN (
    MaPTT CHAR(5) NOT NULL,
    MaHD CHAR(5),
    SoTienDichVu MONEY,
    SoTienThuePT MONEY,
    TongTienTT MONEY,
    NgayTinhTien SMALLDATETIME,
    TinhTrangTT NVARCHAR(20),
    PhuongThucTT NVARCHAR(20),
    CONSTRAINT PK_PHIEUTINHTIEN PRIMARY KEY (MaPTT),
    CONSTRAINT FK_PHIEUTINHTIEN_HOPDONG FOREIGN KEY (MaHD) REFERENCES HOPDONG (MaHD)
);

CREATE TABLE CHITIETTTDV (
    MaPTT CHAR(5) NOT NULL,
    MaDV CHAR(5) NOT NULL,
    ChiSoDV FLOAT,
    ThanhTien MONEY,
    CONSTRAINT PK_CHITIETTTDV PRIMARY KEY (MaPTT, MaDV),
    CONSTRAINT FK_CHITIETTTDV_PHIEUTINHTIEN FOREIGN KEY (MaPTT) REFERENCES PHIEUTINHTIEN (MaPTT),
    CONSTRAINT FK_CHITIETTTDV_DICHVU FOREIGN KEY (MaDV) REFERENCES DICHVU (MaDV)
);
