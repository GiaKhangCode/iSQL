import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {JSDOM} from 'jsdom';
import {writeFile,unlink} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
const dom=new JSDOM('<div id="root"></div>',{url:'http://localhost'});
for(const key of ['window','document','HTMLElement','Element','Node'])globalThis[key]=dom.window[key];
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
const result=await build({stdin:{contents:`export {act,createElement} from 'react';export {createRoot} from 'react-dom/client';export {Simulate} from 'react-dom/test-utils';export {ListSearchInput} from './src/shared/components/ListSearchInput';export {matchesDateRange} from './src/shared/components/ListDateFilters';export {sortAscending} from './src/shared/components/ListSortSelect';export {matchesListSearch} from './src/shared/lib/listSearch';`,resolveDir:process.cwd(),loader:'tsx'},bundle:true,write:false,platform:'node',format:'cjs',jsx:'automatic',loader:{'.css':'empty'},define:{'import.meta.hot':'undefined'}});
const file=join(tmpdir(),`list-search-date-${process.pid}.cjs`);await writeFile(file,result.outputFiles[0].contents);
let root;
try{
 const api=createRequire(import.meta.url)(file);
 const unsorted=[{code:'L10'},{code:'L2'},{code:'L1'}];
 assert.deepEqual(api.sortAscending(unsorted,item=>item.code).map(item=>item.code),['L1','L2','L10']);
 assert.deepEqual(unsorted.map(item=>item.code),['L10','L2','L1'],'Sorting never mutates the default order');
 assert.ok(api.matchesListSearch('  quan LY 252 ','252','Quản lý bán hàng'));
 assert.ok(!api.matchesListSearch('missing','Quản lý'));
 assert.ok(api.matchesDateRange('2026-11-04T18:00:00Z',{from:'2026-11-05',to:'2026-11-05'}),'Date boundaries use Vietnam time');
 assert.ok(!api.matchesDateRange(null,{from:'2026-11-05',to:''}),'Unknown dates are never invented');
 assert.ok(api.matchesDateRange(null,{from:'',to:''}));
 let selected;
 root=api.createRoot(document.getElementById('root'));
 await api.act(async()=>root.render(api.createElement(api.ListSearchInput,{value:'quan ly',label:'Search',onChange:value=>{selected=value;},items:[{id:'1',title:'Quản lý bán hàng',description:'252'},{id:'2',title:'Another item'}]})));
 const input=document.querySelector('input');
 await api.act(async()=>api.Simulate.focus(input));
 assert.equal(document.querySelectorAll('[role=option]').length,1);
 await api.act(async()=>api.Simulate.keyDown(input,{key:'ArrowDown',nativeEvent:{}}));
 await api.act(async()=>api.Simulate.keyDown(input,{key:'Enter',nativeEvent:{}}));
 assert.equal(selected,'Quản lý bán hàng');
 assert.equal(input.getAttribute('aria-expanded'),'false');
 await api.act(async()=>api.Simulate.focus(input));
 await api.act(async()=>api.Simulate.keyDown(input,{key:'Escape',nativeEvent:{}}));
 assert.equal(input.getAttribute('aria-expanded'),'false');
 console.log('PASS: accent-insensitive multi-term search, Vietnam date boundaries, unknown dates, suggestions, keyboard selection and dismissal.');
}finally{if(root)await createRequire(import.meta.url)(file).act(async()=>root.unmount());await unlink(file);dom.window.close();}
process.exit(0);
